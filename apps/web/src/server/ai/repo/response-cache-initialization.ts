import type { DurableObjectStorage } from "@cloudflare/workers-types";
import { drizzle } from "drizzle-orm/durable-sqlite";
import { migrate } from "drizzle-orm/durable-sqlite/migrator";

import baseline from "./response-cache-migrations/0000_legacy_baseline.sql?raw";
import journal from "./response-cache-migrations/meta/_journal.json";

export async function initializeResponseCache(storage: DurableObjectStorage) {
  const baselineEntry = journal.entries[0];
  if (!baselineEntry)
    throw new Error("Missing Durable Object baseline migration");
  // Catalog SQL is needed before Drizzle can adopt a pre-journal object.
  const hasJournal =
    storage.sql
      .exec(
        "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = '__drizzle_migrations'",
      )
      .toArray().length > 0;
  const adopted =
    hasJournal &&
    storage.sql
      .exec(
        "SELECT 1 FROM __drizzle_migrations WHERE created_at = ? LIMIT 1",
        baselineEntry.when,
      )
      .toArray().length > 0;
  // Later migrations may legitimately change these shapes. Check only adoption.
  if (!adopted) {
    const tables = {
      responses: [
        ["key", "TEXT", 0, 1],
        ["value", "TEXT", 0, 0],
        ["expires_at", "INTEGER", 0, 0],
        ["claim_token", "TEXT", 0, 0],
        ["lease_expires_at", "INTEGER", 0, 0],
      ],
      response_chunks: [
        ["key", "TEXT", 1, 1],
        ["seq", "INTEGER", 1, 2],
        ["value", "TEXT", 1, 0],
      ],
    };
    for (const [table, expected] of Object.entries(tables)) {
      const columns = storage.sql
        .exec(`PRAGMA table_xinfo('${table}')`)
        .toArray();
      if (!columns.length) continue;
      if (
        columns.length !== expected.length ||
        expected.some(([name, type, notNull, pk], index) => {
          const column = columns[index];
          return (
            !column ||
            column.name !== name ||
            column.type !== type ||
            column.pk !== pk ||
            // SQLite's legacy TEXT PRIMARY KEY reports notnull=0. String key producers
            // also work with the explicit NOT NULL generated by Drizzle for new stores.
            (column.notnull !== notNull &&
              !(pk === 1 && notNull === 0 && column.notnull === 1)) ||
            column.dflt_value !== null
          );
        })
      )
        throw new Error(
          `Incompatible AI response cache legacy table: ${table}`,
        );
    }
  }
  await migrate(drizzle(storage), { journal, migrations: { m0000: baseline } });
}
