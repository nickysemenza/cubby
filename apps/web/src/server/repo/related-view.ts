type PreviewRow = z.infer<typeof previewRowSchema>;

async function loadOneRows(
  db: Database,
  relationKey: RelatedViewKey,
  sourceIds: string[],
): Promise<PreviewRow[]> {
  const view = sqlRelatedView(relationKey);
  const ids = sql.join(
    sourceIds.map((id) => sql`${id}`),
    sql`, `,
  );
  const query = sql`
    WITH related AS (
      SELECT DISTINCT
        s."shortcode" AS "sourceId",
        t."id"::text AS "targetEntityId",
        t."shortcode" AS "id",
        ${sql.raw(view.label)}::text AS "label",
        ${sql.raw(view.sort)} AS "sortValue"
      FROM ${sql.raw(`"${view.sourceTable}"`)} s
      ${compiledRelatedJoins(relationKey)}
      WHERE s."shortcode" IN (${ids}) AND s."deletedAt" IS NULL
        ${viewWhere(view)}
    ), ranked AS (
      SELECT *,
        count(*) OVER (PARTITION BY "sourceId")::int AS "totalCount",
        row_number() OVER (
          PARTITION BY "sourceId"
          ORDER BY "sortValue" ${sql.raw(view.sortDirection)}, "label", "id"
        ) AS rn
      FROM related
    )
    SELECT "sourceId", "targetEntityId", "id", "label", "totalCount"
    FROM ranked
    WHERE rn <= 3
    ORDER BY "sourceId", rn
  `;
  const result = await getDb(db).execute(query);
  return previewRowSchema.array().parse(result.rows);
}

export async function loadRelatedPreviews(
  db: Database,
  input: RelatedPreviewInput,
): Promise<RelatedPreviewGroup[]> {
  const allowed = new Set(
    relatedViewRegistry
      .filter((view) => view.source === input.source)
      .map((view) => view.key),
  );
  const relationKeys = uniq(input.relationKeys).filter((key) =>
    allowed.has(key),
  );
  if (input.sourceIds.length === 0 || relationKeys.length === 0) return [];
  const loaded = await Promise.all(
    relationKeys.map(async (key) => ({
      relationKey: key,
      rows: await loadOneRows(db, key, uniq(input.sourceIds)),
    })),
  );
  const displayImages = await resolveEntityDisplayImages(
    db,
    loaded.flatMap(({ relationKey, rows }) => {
      const targetEntity = sqlRelatedView(relationKey).targetEntity;
      return rows.map((row) => ({
        entityType: targetEntity,
        entityId: row.targetEntityId,
      }));
    }),
  );
  return loaded.flatMap(({ relationKey, rows }) => {
    const targetEntity = sqlRelatedView(relationKey).targetEntity;
    const grouped = new Map<string, RelatedPreviewGroup>();
    for (const row of rows) {
      const group = grouped.get(row.sourceId) ?? {
        sourceId: row.sourceId,
        relationKey,
        totalCount: Number(row.totalCount),
        items: [],
      };
      group.items.push({
        entity: targetEntity,
        id: row.id,
        label: row.label,
        displayImage:
          displayImages.get(entityRefKey(targetEntity, row.targetEntityId)) ??
          null,
      });
      grouped.set(row.sourceId, group);
    }
    return [...grouped.values()];
  });
}

/**
 * Load a single, paginated branch for the relationship outline. This shares
 * the exact SQL realization used by table previews and predicates, so there
 * is no parallel interpretation of a relationship in the UI layer.
 */
export async function loadRelatedBranch(
  db: Database,
  input: RelatedBranchInput,
): Promise<RelatedBranchOutput> {
  const view = sqlRelatedView(input.relationKey);
  const query = sql`
    WITH related AS (
      SELECT DISTINCT
        t."id"::text AS "targetEntityId",
        t."shortcode" AS "id",
        ${sql.raw(view.label)}::text AS "label",
        ${sql.raw(view.sort)} AS "sortValue"
      FROM ${sql.raw(`"${view.sourceTable}"`)} s
      ${compiledRelatedJoins(input.relationKey)}
      WHERE s."shortcode" = ${input.sourceId} AND s."deletedAt" IS NULL
        ${viewWhere(view)}
    ), ranked AS (
      SELECT *, count(*) OVER ()::int AS "totalCount"
      FROM related
    )
    SELECT "targetEntityId", "id", "label", "sortValue", "totalCount"
    FROM ranked
    ORDER BY "sortValue" ${sql.raw(view.sortDirection)}, "label", "id"
    LIMIT ${input.limit} OFFSET ${input.offset}
  `;
  const result = await getDb(db).execute(query);
  const rows = branchRowSchema.array().parse(result.rows);
  const displayImages = await resolveEntityDisplayImages(
    db,
    rows.map((row) => ({
      entityType: view.targetEntity,
      entityId: row.targetEntityId,
    })),
  );
  const totalCount = rows.length ? Number(rows[0]?.totalCount) : 0;
  const consumed = input.offset + rows.length;
  return {
    sourceId: input.sourceId,
    relationKey: input.relationKey,
    totalCount,
    items: rows.map((row) => ({
      entity: view.targetEntity,
      id: row.id,
      label: row.label,
      displayImage:
        displayImages.get(
          entityRefKey(view.targetEntity, row.targetEntityId),
        ) ?? null,
    })),
    nextOffset: consumed < totalCount ? consumed : null,
  };
}

/** Search targets for a relation, including the number of distinct sources. */
/**
 * ORDER BY expression for a `related:<key>` column, built from the SAME joins,
 * sort expression, and `where` the cell reads — so a change to the view moves
 * the sort with it.
 *
 * Before this, `product/crud.ts` restated all three of its related traversals
 * by hand. That is how `product.purchases` came to need a second, manual edit
 * the moment the view gained its acquisition predicate: the sort would
 * otherwise have ranked rows by a disposal date absent from every cell it
 * sorts.
 *
 * The aggregate follows the view's own `sortDirection`, which makes it "rank by
 * the FIRST chip the cell shows": a DESC view (purchases, by date) previews its
 * newest row, so `max`; an ASC view (vendors, by name) previews its
 * alphabetically first, so `min`. `direction` then orders those keys. This is
 * why a descending vendor sort reverses by each product's first vendor rather
 * than ranking by its last — deliberate, and now derived rather than restated.
 *
 * `rootIdRef` is the enclosing query's id reference, hand-qualified by the
 * caller (`"product"."id"` under the relational query builder). `renderJoins`
 * emits `sql.raw` exclusively, so the whole clause survives both
 * `buildSelection`'s prefix stripping and the RQB's alias rewriting.
 */
export const relatedSortExpression = (
  relationKey: RelatedViewKey,
  rootIdRef: string,
): SQL => {
  const view = sqlRelatedView(relationKey);
  const aggregate = view.sortDirection === "DESC" ? "max" : "min";
  return sql`(SELECT ${sql.raw(aggregate)}(${sql.raw(view.sort)})
    FROM ${sql.raw(`"${view.sourceTable}"`)} s
    ${compiledRelatedJoins(relationKey)}
    WHERE s."id" = ${sql.raw(rootIdRef)} AND s."deletedAt" IS NULL
      ${viewWhere(view)})`;
};

export async function loadRelatedOptions(
  db: Database,
  input: RelatedOptionsInput,
): Promise<RelatedOptionsOutput> {
  const view = sqlRelatedView(input.relationKey);
  const search = input.search?.trim();
  const query = sql`
    SELECT
      t."shortcode" AS "id",
      ${sql.raw(view.label)}::text AS "label",
      count(DISTINCT s."id")::int AS "count"
    FROM ${sql.raw(`"${view.sourceTable}"`)} s
    ${compiledRelatedJoins(input.relationKey)}
    WHERE s."deletedAt" IS NULL
      ${viewWhere(view)}
      ${search ? sql`AND ${sql.raw(view.label)} ILIKE ${`%${search}%`}` : sql``}
    GROUP BY t."shortcode", ${sql.raw(view.label)}
    ORDER BY "label", "id"
    LIMIT ${input.limit}
  `;
  const result = await getDb(db).execute(query);
  const rows = optionRowSchema.array().parse(result.rows);
  return rows.map((row) => ({
    entity: view.targetEntity,
    id: row.id,
    label: row.label,
    count: Number(row.count),
  }));
}

