interface RelatedViewSqlPresentation {
  label: string;
  sort: string;
  sortDirection: "ASC" | "DESC";
  /**
   * Extra restriction on which traversal rows the view admits, ANDed into
   * EVERY consumer below — preview, branch, options, and the list filter — so
   * a view can never mean one thing in a cell and another in a sort.
   *
   * Written against the stable `s` (source) and `t` (target) aliases only.
   * Intermediate hop aliases are generated by `compileTraversal` and are not
   * part of any contract.
   */
  where?: string;
}

