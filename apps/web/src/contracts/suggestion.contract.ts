import {
  fieldAuthorityActionInput,
  fieldAuthorityActionOut,
  fieldGuessInput,
  fieldGuessOut,
} from "@cubby/schemas/field-authority";
import {
  suggestionReviewInput,
  suggestionReviewOut,
  suggestionReviewBatchInput,
  suggestionReviewBatchOut,
} from "@cubby/schemas/suggestion";

import { defineContract, mutation, query } from "~/contracts/define";

export const suggestionContract = defineContract(
  "suggestion",
  {
    review: mutation({
      description:
        "Review immutable evidence as correct, wrong, uncertain or a presentation dismissal. Draft review does not apply; saved application is revalidated. Applying anything other than the recommendation as is (another action, kind or booking) is a correction: verdict wrong with correction {present:true, value:<the full application>}, where value equals the application sent.",
      input: suggestionReviewInput,
      output: suggestionReviewOut,
      invalidates: [
        "product",
        "expense",
        "purchase",
        "vendor",
        "email",
        "image",
        "recommendations",
        "settledSuggestions",
        "suggestions",
        "connections",
        "task",
        "project",
        "inventory",
        "location",
        "meal",
        "planting",
        "gardenEntry",
        "productCategory",
        "spendingCategory",
        "cookbook",
        "sourceTransactionRecord",
        "financialTransaction",
      ],
    }),
    fieldGuess: query({
      description:
        "Cubby's current answer for one field of a saved record, shown first in the field's picker. Null when Cubby has no answer or a person holds the field.",
      input: fieldGuessInput,
      output: fieldGuessOut,
    }),
    fieldAuthority: mutation({
      description:
        "Keep a value Cubby set (it becomes yours), clear a wrong value Cubby set so it can try again, or release your value so Cubby may decide this field.",
      input: fieldAuthorityActionInput,
      output: fieldAuthorityActionOut,
      invalidates: [
        "product",
        "expense",
        "purchase",
        "vendor",
        "task",
        "project",
        "inventory",
        "location",
        "meal",
        "planting",
        "gardenEntry",
        "productCategory",
        "spendingCategory",
        "cookbook",
        "financialAccount",
        "financialTransaction",
        "suggestions",
      ],
    }),
    reviewBatch: mutation({
      exposure: "view",
      note: "Agents review one or many Suggestions through suggestions.review items",
      description:
        "Review Suggestions independently; each item returns its own outcome.",
      command: { label: "Review suggestions", confirmation: null },
      input: suggestionReviewBatchInput,
      output: suggestionReviewBatchOut,
      invalidates: [
        "product",
        "expense",
        "purchase",
        "vendor",
        "email",
        "image",
        "recommendations",
        "settledSuggestions",
        "suggestions",
        "connections",
        "task",
        "project",
        "inventory",
        "location",
        "meal",
        "planting",
        "gardenEntry",
        "productCategory",
        "spendingCategory",
        "cookbook",
        "sourceTransactionRecord",
        "financialTransaction",
      ],
    }),
  },
  { exposure: "capability", mcpToolGroup: "suggestions" },
);
