// Bundles recipebridge-host/host.js (wasm-bindgen glue + base64 WASM + the RPC
// shim) into ONE self-contained <script>, wrapped in a tiny HTML document, and
// emits it as a generated TS module the app imports and feeds to a hidden WebView.
// Re-run after bumping @cubby/recipebridge: `pnpm --filter @cubby/mobile build:recipebridge-host`.
import { statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "src/lib/recipebridge-host.generated.ts");

// Up-to-date guard: skip the (slow) rebuild if the generated file is newer than
// both the host source and the WASM it inlines. Lets metro.config.js call this on
// every bundler start cheaply. Pass --force to always rebuild.
const wasmPath = createRequire(import.meta.url).resolve(
  "@cubby/recipebridge/recipebridge_bg.wasm",
);
const hostPath = join(root, "recipebridge-host/host.js");
const mtime = (p) => {
  try {
    return statSync(p).mtimeMs;
  } catch {
    return Number.POSITIVE_INFINITY; // missing input → treat as "newer" so we rebuild
  }
};
if (
  !process.argv.includes("--force") &&
  mtime(out) >= Math.max(mtime(wasmPath), mtime(hostPath)) &&
  Number.isFinite(mtime(out))
) {
  process.exit(0); // up to date
}

const result = await esbuild.build({
  entryPoints: [join(root, "recipebridge-host/host.js")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "safari15",
  minify: true,
  write: false,
  loader: { ".wasm": "base64" }, // inline the WASM so the WebView is fully offline
});

// Escape `</script>` so the inlined JS can't break out of the HTML <script>.
const js = result.outputFiles[0].text.replace(/<\/script>/gi, "<\\/script>");
const html = `<!doctype html><html><head><meta charset="utf-8"></head><body><script>${js}</script></body></html>`;

const ts =
  "// AUTO-GENERATED by scripts/build-recipebridge-host.mjs — do not edit.\n" +
  "// biome-ignore-all lint: generated\n" +
  `export const RECIPEBRIDGE_HOST_HTML = ${JSON.stringify(html)};\n`;

writeFileSync(out, ts);
console.log(`wrote ${out} (${(ts.length / 1024 / 1024).toFixed(2)} MB)`);
